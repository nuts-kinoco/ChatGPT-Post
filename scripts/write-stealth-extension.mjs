import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { STEALTH_SIGNAL_PATCH } from "../dist/browser/stealth-signals.js";

const repoRoot = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const output = join(repoRoot, "experimental", "stealth-extension", "content.js");
const generated = `// Generated by scripts/write-stealth-extension.mjs from src/browser/stealth-signals.ts.\n// Do not edit this file directly.\n${STEALTH_SIGNAL_PATCH}`;

await writeFile(output, generated, "utf8");
