export function safeIssuerError(error: unknown): string {
  try {
    if (error && typeof error === "object") {
      const value = error as { code?: unknown; message?: unknown };
      // Accessor-backed exceptions are untrusted. Capture each field at most once.
      const code = value.code;
      if (typeof code === "string" && SAFE_ISSUER_ERRORS.has(code)) return code;
      const message = value.message;
      if (typeof message === "string" && SAFE_ISSUER_ERRORS.has(message)) return message;
    }
  } catch {
    // A throwing getter cannot bypass redaction or replace the finite diagnostic.
  }
  return "issuer_operation_failed";
}
